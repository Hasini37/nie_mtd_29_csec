@app.post(
    "/customer/tickets",
    status_code=201
)
def customer_create_ticket(
    payload: TicketCreate,
    current_user=Depends(
        require_role(CUSTOMER)
    )
):

    # Check order ID

    if not ObjectId.is_valid(payload.order_id):

        raise HTTPException(
            status_code=400,
            detail="Invalid order ID"
        )

    order = order_collection.find_one({
        "_id": ObjectId(payload.order_id)
    })

    if order is None:

        raise HTTPException(
            status_code=404,
            detail="Order not found"
        )

    # Check order belongs to customer

    if order["customer_id"] != str(
        current_user["_id"]
    ):

        raise HTTPException(
            status_code=403,
            detail="This order does not belong to you"
        )

    ticket_data = {

        "customer_id": str(
            current_user["_id"]
        ),

        "order_id": payload.order_id,

        "title": payload.title,

        "description": payload.description,

        "category": payload.category,

        "status": "NEW",

        "agent_id": None
    }

    result = ticket_collection.insert_one(
        ticket_data
    )

    return {
        "message": "Support ticket created successfully",
        "ticket_id": str(result.inserted_id)
    }


