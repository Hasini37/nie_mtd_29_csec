# CREATE JWT TOKEN

def create_token(username: str, role: int): 
#expire tells you the duration for open window of an website(ex moodle)
    expire = datetime.now(timezone.utc) + timedelta(
        minutes=TOKEN_EXPIRE_MINS
    )

#payload gives some info to the token generated 
    payload = {
        "sub": username,
        "role": role,
        "exp": expire
    }

#here jwt creates the actual tocken using secret key
#.encode is a fn of jwt lib, it takes info and creates jwt token by itself
    token = jwt.encode(
        payload,
        SECRET_KEY,
        algorithm=ALGORITHM
    )

    return token

# GET CURRENT USER

def get_current_user(
    token: str = Depends(oauth2_scheme)
):

    try:
        #.decode reads info in side token and verify it
        payload = jwt.decode(
            token,
            SECRET_KEY,
            algorithms=[ALGORITHM]
        )

        username = payload.get("sub")
        role = payload.get("role")

        if username is None or role is None:

            raise HTTPException(
                status_code=401,
                detail="Invalid token"
            )

    except jwt.ExpiredSignatureError:

        raise HTTPException(
            status_code=401,
            detail="Token has expired"
        )

    except jwt.InvalidTokenError:

        raise HTTPException(
            status_code=401,
            detail="Invalid token"
        )

    user = user_collection.find_one(
        {"username": username}
    )

    if user is None:

        raise HTTPException(
            status_code=404,
            detail="User not found"
        )

    return user


# ROLE CHECK

def require_role(*allowed_roles):

    def check_role(
        current_user=Depends(get_current_user)
    ):

        if current_user["role"] not in allowed_roles:

            raise HTTPException(
                status_code=403,
                detail="Permission denied"
            )

        return current_user

    return check_role


# 1. USER REGISTRATION


@app.post(
    "/users",
    status_code=201
)
def create_user(user: UserCreate):

    # Check valid role

    if user.role not in [
        CUSTOMER,
        SUPPORT_AGENT,
        TEAM_LEAD,
        ADMIN
    ]:

        raise HTTPException(
            status_code=400,
            detail="Invalid role"
        )

    existing_user = user_collection.find_one(
        {"username": user.username}
    )

    if existing_user:

        raise HTTPException(
            status_code=409,
            detail="Username already exists"
        )

    hashed_password = password_hash.hash(
        user.password
    )

    user_data = {

        "username": user.username,

        "password": hashed_password,

        "role": user.role
    }

    result = user_collection.insert_one(
        user_data
    )

    new_user = user_collection.find_one(
        {"_id": result.inserted_id}
    )

    return user_helper(new_user)


# 2. LOGIN


@app.post(
    "/login",
    response_model=TokenResponse
)
def login(
    form_data: OAuth2PasswordRequestForm = Depends()
):

    user = user_collection.find_one(
        {"username": form_data.username}
    )

    if user is None:

        raise HTTPException(
            status_code=401,
            detail="Invalid username or password"
        )

    if not password_hash.verify(
        form_data.password,
        user["password"]
    ):

        raise HTTPException(
            status_code=401,
            detail="Invalid username or password"
        )

    token = create_token(
        user["username"],
        user["role"]
    )

    return {
        "access_token": token,
        "token_type": "bearer"
    }


